def build_cases(triples, trap_type):
    return [
        {
            "id": f"pat_{trap_type}_{i+1:03d}",
            "trap_type": trap_type,
            "clause_a": a,
            "clause_b": b,
            "clause_c": c,
        }
        for i, (a, b, c) in enumerate(triples)
    ]


def main():
    if len(sys.argv) < 2:
        print(f"usage: {sys.argv[0]} <output_json_path>", file=sys.stderr)
        sys.exit(2)
    out_path = Path(sys.argv[1])

    cases = []
    cases += build_cases(CLAIM_SCOPE_TRIPLES, "claim_scope_flip")
    cases += build_cases(ENABLEMENT_TRIPLES, "enablement_flip")
    cases += build_cases(ART_FLIP_TRIPLES, "art_flip")
    cases += build_cases(MECHANISM_TRIPLES, "mechanism_substitution")

    print(f"[gen] built {len(cases)} triples", file=sys.stderr)
    from collections import Counter
    tt = Counter(c["trap_type"] for c in cases)
    print(f"[gen] taxonomy: {dict(tt)}", file=sys.stderr)

    print(f"[gen] checking distinctness...", file=sys.stderr)
    check_distinct(cases)
    print(f"[gen] distinctness OK", file=sys.stderr)

    print(f"[gen] checking shape invariants (6-30 words, matched)...", file=sys.stderr)
    check_shape(cases)
    print(f"[gen] shape OK", file=sys.stderr)

    output = {
        "_source": "Hand-authored triples covering four USPTO-relevant trap types.",
        "_shape_contract": (
            "All A/B/C 6-30 words, matched-shape (max/min word count <= 2.0). "
            "B differs from A by ONE meaningful token reversing meaning. "
            "C paraphrases A in different surface wording, same intent."
        ),
        "_trap_taxonomy": {
            "claim_scope_flip": "'comprising' (open) ↔ 'consisting of' (closed) — patent claim scope",
            "enablement_flip": "enabled/capable ↔ disabled/incapable — 35 U.S.C. § 112 enablement",
            "art_flip": "novel/prior art ↔ known/subsequent — 35 U.S.C. § 102/103 novelty",
            "mechanism_substitution": "domain-verb swap (encrypt↔decrypt, activate↔inhibit, etc.)",
        },
        "_taxonomy_counts": dict(tt),
        "test_cases": cases,
    }
    out_path.write_text(json.dumps(output, indent=2))
    print(f"[gen] wrote {out_path} ({out_path.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
