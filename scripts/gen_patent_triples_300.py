"""Generate the matched-shape patent A/B/C triples.

Four trap types (75 each):
  claim_scope_flip     — "comprising" (open) ↔ "consisting of" (closed).
                         Fundamental patent-scope legal distinction.
  enablement_flip      — enabled/capable ↔ disabled/incapable. 35 U.S.C. § 112.
  art_flip             — novel/prior art ↔ known/well-known. 35 U.S.C. § 102/103.
  mechanism_substitution — domain-verb swap (encrypt↔decrypt, activate↔inhibit,
                           couple↔decouple, transmit↔receive, heat↔cool, ...).

Shape invariants (paper §3.1):
  A, B, C all 6-30 words, matched-shape (max/min word count <= 2.0)
  B differs from A by ONE meaningful token that reverses meaning
  C paraphrases A preserving intent
  No clause_a duplicates within batch, across trap types

Same generator schema as scripts/gen_medical_triples_200.py.
"""
import json
import sys
from pathlib import Path


def word_count(s):
    return len(s.split())


def check_shape(cases, wmin=6, wmax=30):
    violations = []
    for i, c in enumerate(cases):
        for field in ("clause_a", "clause_b", "clause_c"):
            n = word_count(c[field])
            if n < wmin or n > wmax:
                violations.append(
                    f"  case {i} ({c['trap_type']}) {field}={n} words: {c[field][:70]}..."
                )
        la, lb, lc = word_count(c["clause_a"]), word_count(c["clause_b"]), word_count(c["clause_c"])
        if max(la, lb, lc) > 2.0 * min(la, lb, lc):
            violations.append(
                f"  case {i} ({c['trap_type']}) shape a={la} b={lb} c={lc}: {c['clause_c'][:70]}..."
            )
    if violations:
        raise ValueError(
            f"{len(violations)} shape violations:\n" + "\n".join(violations)
        )
    return True


def check_distinct(cases):
    seen = set()
    for c in cases:
        key = c["clause_a"].strip().lower()
        if key in seen:
            raise ValueError(f"duplicate clause_a: {c['clause_a']}")
        seen.add(key)


