"""Generate the matched-shape financial A/B/C triples.

Four trap types (75 each):
  direction_flip:   increased ↔ decreased, grew ↔ declined, etc.
  polarity_flip:    gain ↔ loss, profit ↔ loss, asset ↔ liability, credit ↔ debit
  period_flip:      Q1 ↔ Q4, fiscal 2023 ↔ 2024, current ↔ prior, YoY ↔ QoQ
  party_flip:       lender ↔ borrower, buyer ↔ seller, acquirer ↔ target

Same schema as gen_patent_triples_300.py.
"""
import json
import sys
from pathlib import Path


def word_count(s):
    return len(s.split())


def check_shape(cases, wmin=6, wmax=30):
    violations = []
    for i, c in enumerate(cases):
        for field in ("clause_a", "clause_b", "clause_c"):
            n = word_count(c[field])
            if n < wmin or n > wmax:
                violations.append(f"  case {i} ({c['trap_type']}) {field}={n}w: {c[field][:70]}")
        la, lb, lc = word_count(c["clause_a"]), word_count(c["clause_b"]), word_count(c["clause_c"])
        if max(la, lb, lc) > 2.0 * min(la, lb, lc):
            violations.append(f"  case {i} shape a={la} b={lb} c={lc}: {c['clause_c'][:70]}")
    if violations:
        raise ValueError(f"{len(violations)} shape violations:\n" + "\n".join(violations))
    return True


def check_distinct(cases):
    seen = set()
    for c in cases:
        key = c["clause_a"].strip().lower()
        if key in seen:
            raise ValueError(f"duplicate clause_a: {c['clause_a']}")
        seen.add(key)


